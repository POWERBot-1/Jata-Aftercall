#!/usr/bin/env node
/**
 * JATA AFTERCALL — evidence manifest generator
 *
 * Regenerate `docs/release/EVIDENCE-MANIFEST.sha256` after editing any artifact
 * it covers. The manifest deliberately excludes itself: a digest of itself
 * cannot verify, because writing the digest changes the file that produced it.
 *
 * The file list comes from `REQUIRED_ARTIFACTS` in `verify-evidence-manifest.mjs`
 * plus the checker sources themselves, so the manifest and the verifier cannot
 * drift apart.
 *
 * USAGE
 *   node scripts/ci/generate-evidence-manifest.mjs           # rewrite the manifest
 *   node scripts/ci/generate-evidence-manifest.mjs --check    # fail if it is stale
 *
 * EXIT CODES
 *   0  written, or (with --check) already current
 *   1  (with --check) the manifest is stale
 *   2  blocked: a required artifact does not exist
 */

import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { REQUIRED_ARTIFACTS } from "./verify-evidence-manifest.mjs";

export const MANIFEST_PATH = "docs/release/EVIDENCE-MANIFEST.sha256";

/**
 * The manifest covers the evidence artifacts plus the checkers that make the
 * claims quotable. Listing the checkers means a change to a check invalidates
 * the manifest — which is correct, because the claim changes with it.
 */
export const COVERED_SOURCES = [
  "scripts/ci/verify-evidence-manifest.mjs",
  "scripts/ci/generate-evidence-manifest.mjs",
  "scripts/ci/summarise-audit.mjs",
  "scripts/ci/migration-manifest.mjs",
  "scripts/ci/migration-expectations.mjs",
  "scripts/ci/check-schema-drift.mjs",
  "scripts/ci/check-test-output.mjs",
];

const HEADER = [
  "# Evidence manifest — JATA AFTERCALL release review",
  "# Generated by scripts/ci/generate-evidence-manifest.mjs.",
  "# Verify with: sha256sum -c docs/release/EVIDENCE-MANIFEST.sha256",
  "# This file deliberately does not list itself; a digest of itself cannot verify.",
  "",
];

/** Every path the manifest must cover, de-duplicated and sorted. */
export function coveredPaths() {
  const all = [...REQUIRED_ARTIFACTS, ...COVERED_SOURCES];
  return [...new Set(all)].sort();
}

/** Render the manifest text without touching the filesystem. */
export function renderManifest(paths, cwd = process.cwd()) {
  const lines = [...HEADER];
  for (const path of paths) {
    const absolute = `${cwd}/${path}`;
    if (!existsSync(absolute)) throw new Error(`required artifact is missing: ${path}`);
    const hash = createHash("sha256").update(readFileSync(absolute)).digest("hex");
    lines.push(`${hash}  ${path}`);
  }
  return `${lines.join("\n")}\n`;
}

function main(argv) {
  const check = argv.includes("--check");
  let rendered;
  try {
    rendered = renderManifest(coveredPaths());
  } catch (error) {
    console.error(`BLOCKED: ${error.message}`);
    return 2;
  }

  if (check) {
    if (!existsSync(MANIFEST_PATH)) {
      console.error(`FAIL: ${MANIFEST_PATH} does not exist`);
      return 1;
    }
    const current = readFileSync(MANIFEST_PATH, "utf8");
    if (current !== rendered) {
      console.error(`FAIL: ${MANIFEST_PATH} is stale — an artifact it covers has changed.`);
      console.error("      Regenerate with: node scripts/ci/generate-evidence-manifest.mjs");
      return 1;
    }
    console.log(`PASS: ${MANIFEST_PATH} is current (${coveredPaths().length} artifacts).`);
    return 0;
  }

  writeFileSync(MANIFEST_PATH, rendered);
  console.log(`WROTE ${MANIFEST_PATH} — ${coveredPaths().length} artifacts.`);
  return 0;
}

if (process.argv[1] && process.argv[1].endsWith("generate-evidence-manifest.mjs")) {
  process.exit(main(process.argv));
}
