import chromium from "@sparticuz/chromium";
import { chromium as pw } from "playwright-core";
const b = await pw.launch({ executablePath: await chromium.executablePath(), args: chromium.args.filter(a => !["--single-process","--no-zygote"].includes(a)), headless: true, env: { ...process.env, LD_LIBRARY_PATH: "/tmp/al/lib" } });
const p = await (await b.newContext({ viewport: { width: 390, height: 844 } })).newPage();
const errs = [], net = [];
p.on("pageerror", e => errs.push(e.message));
p.on("request", r => { if (r.url().includes("/api/")) net.push(r.method() + " " + new URL(r.url()).pathname); });
await p.goto("http://localhost:3000/dev/ai-front-desk-fixture?outcome=success", { waitUntil: "load", timeout: 240000 });
await p.waitForSelector("text=AI Business Front Desk", { timeout: 120000 });
await p.waitForTimeout(800);
console.log("welcome ok; steps:", await p.getByRole("button", { name: /Preview/ }).count());
await p.getByRole("button", { name: /Preview/ }).first().click();
await p.waitForSelector("#fd-test-question", { timeout: 60000 });
await p.fill("#fd-test-question", "Do you deliver to Kitengela?");
await p.getByRole("button", { name: "Send test question" }).click();
await p.waitForTimeout(200);
console.log("loading status:", await p.locator('[role="status"]').allInnerTexts());
await p.waitForTimeout(1800);
console.log("after reply:", (await p.locator("body").innerText()).match(/SIMULATED FIXTURE REPLY[^\n]*/g));
console.log("errors:", errs, "api:", net);
await b.close();
