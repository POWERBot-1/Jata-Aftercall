/**
 * Owner QR identity panel (Business Hub E).
 *
 * Shows exactly what will be printed and offers the three downloads: PNG for artwork and
 * packaging, SVG for anything that will be scaled, and the A4 poster for a shopfront or counter.
 *
 * The preview and every download are produced from the same function, so what the owner sees is
 * what they print. The encoded URL is printed underneath in plain text — a QR code is a
 * convenience, never the only way onto the page.
 */

import { businessQrSvg, publicPageUrl } from "@/lib/business-hub/qrIdentity";
import { QrDownloadButton } from "./QrDownloadButton";

export function QrIdentityPanel({
  businessId,
  slug,
  businessName,
}: {
  businessId: string;
  slug: string;
  businessName: string;
}) {
  const url = publicPageUrl(slug);
  const svg = businessQrSvg(slug, { size: 260 });
  const domId = `owner-qr-${slug.replace(/[^a-z0-9-]/gi, "")}`;

  return (
    <div className="space-y-4">
      <div className="jata-card">
        <div className="flex flex-col items-center gap-4 sm:flex-row sm:items-start">
          <div
            id={domId}
            className="rounded-2xl border border-zinc-200 bg-white p-3"
            // Generated by lib/qr/encoder.ts from the page slug: no owner input reaches the markup.
            dangerouslySetInnerHTML={{ __html: svg }}
          />
          <div className="min-w-0 flex-1">
            <h2 className="text-sm font-bold">{businessName}</h2>
            <p className="mt-1 break-all text-sm text-zinc-600">{url}</p>
            <p className="jata-hint mt-2">
              This code always opens your published Business Page. Editing your profile, catalogue or promotions cannot
              change where it points, so you never have to reprint after a content change.
            </p>
            <QrDownloadButton targetId={domId} filename={`${slug}-jata-qr`} label="Download QR" />
          </div>
        </div>
      </div>

      <div className="jata-card">
        <h2 className="text-sm font-bold">Print and share</h2>
        <p className="jata-hint mt-1">
          The poster is laid out for A4 at 300 dpi with the business name and the web address under the code. The PNG is
          12 pixels per module with the 4-module quiet zone the QR standard requires.
        </p>
        <div className="jata-quick-actions mt-3">
          <a className="jata-btn jata-btn-primary" href={`/api/business/${businessId}/qr?format=poster&download=1`}>
            Poster (A4 SVG)
          </a>
          <a className="jata-btn jata-btn-secondary" href={`/api/business/${businessId}/qr?format=png&download=1`}>
            High-resolution PNG
          </a>
          <a className="jata-btn jata-btn-secondary" href={`/api/business/${businessId}/qr?format=svg&download=1`}>
            Vector SVG
          </a>
          <a className="jata-btn jata-btn-ghost" href={url} target="_blank" rel="noopener noreferrer">
            Open the page
          </a>
        </div>
        <p className="jata-hint mt-3">
          Suited to posters, packaging, receipts, menus and storefront displays. The code contains your public page
          address only — never a dashboard link, an internal id or any customer detail.
        </p>
      </div>
    </div>
  );
}

export default QrIdentityPanel;
